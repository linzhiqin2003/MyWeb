def enrich_card(data: Dict[str, Any]) -> Dict[str, Any]:
    """Overlay canonical meanings onto a serialized TarotCard dict."""
    extra = CARD_MEANINGS.get(data.get("name") or "", {})
    if not extra:
        data.setdefault("name_cn", data.get("name", ""))
        data.setdefault("element", "")
        data.setdefault("yes_no", "maybe")
        return data

    data["name_cn"] = extra["name_cn"]
    data["element"] = extra["element"]
    data["yes_no"] = extra["yes_no"]
    data["keywords"] = extra["keywords"]
    data["meanings_light"] = extra["meanings_light"]
    data["meanings_shadow"] = extra["meanings_shadow"]
    data["fortune_telling"] = extra["fortune_telling"]
    return data


def meaning_for(name: str, reversed: bool = False) -> str:
    extra = CARD_MEANINGS.get(name, {})
    key = "meanings_shadow" if reversed else "meanings_light"
    lines = extra.get(key) or extra.get("meanings_light") or []
    return "；".join(lines)
